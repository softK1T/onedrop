export const EXPENSE_MESSAGES: Record<Locale, Record<string, string>> = { en, ru, pl, uk };

export function expenseLabel(locale: string | null | undefined, key: string): string {
  const short = (locale ?? DEFAULT_LOCALE).split('-')[0]?.toLowerCase() ?? DEFAULT_LOCALE;
  const resolved = (SUPPORTED_LOCALES as readonly string[]).includes(short)
    ? (short as Locale)
    : DEFAULT_LOCALE;
  return EXPENSE_MESSAGES[resolved][key] ?? EXPENSE_MESSAGES[DEFAULT_LOCALE][key] ?? key;
}
